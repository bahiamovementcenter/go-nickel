#!/bin/sh
# Replaces lib/ and include/nickel_lang.h with the C library of a rust-nickel
# release, and regenerates link.go from the link flags each archive lists.
#
#   scripts/update-lib.sh v0.1.0             # downloads the release from GitHub
#   scripts/update-lib.sh v0.1.0 DIR         # uses archives already in DIR
#
# The archives are checked against the release's SHA256SUMS.
set -eu

version=${1:?usage: scripts/update-lib.sh vX.Y.Z [DIR]}
platforms="linux_amd64 linux_arm64 darwin_arm64 windows_amd64"
repo=https://github.com/bahiamovementcenter/rust-nickel
cd "$(dirname "$0")/.."

work=$(mktemp -d)
trap 'rm -r "$work"' EXIT

if [ $# -ge 2 ]; then
  cp "$2"/nickel-embed-capi-"$version"-*.tar.gz "$2"/SHA256SUMS "$work"/
else
  for p in $platforms; do
    curl -sSfL -o "$work/nickel-embed-capi-$version-$p.tar.gz" \
      "$repo/releases/download/$version/nickel-embed-capi-$version-$p.tar.gz"
  done
  curl -sSfL -o "$work/SHA256SUMS" "$repo/releases/download/$version/SHA256SUMS"
fi
(cd "$work" && sha256sum --check --strict SHA256SUMS)

{
  echo "// Code generated by scripts/update-lib.sh from rust-nickel $version. DO NOT EDIT."
  echo
  echo "package ncl"
  echo
  echo "// Links the C library of nickel-embed (rust-nickel's nickel-embed-capi), committed in"
  echo "// lib/ for each platform, with the system libraries it needs."
  echo
  echo "/*"
} > "$work/link.go"

for p in $platforms; do
  name="nickel-embed-capi-$version-$p"
  tar -xzf "$work/$name.tar.gz" -C "$work"
  mkdir -p "lib/$p"
  cp "$work/$name/libnickel_lang.a" "lib/$p/libnickel_lang.a"
  # The Windows build checks the header out with CRLF line endings.
  tr -d '\r' < "$work/$name/nickel_lang.h" > "$work/$name/header.lf"
  if [ -f "$work/header.h" ]; then
    cmp -s "$work/header.h" "$work/$name/header.lf" || {
      echo "$p: nickel_lang.h differs from the other platforms'" >&2
      exit 1
    }
  else
    cp "$work/$name/header.lf" "$work/header.h"
  fi
  goos=${p%_*}
  goarch=${p#*_}
  # The C compiler adds -lc itself; the rest is what the archive needs. On Windows, rustc names
  # import libraries that come with Rust crates rather than MinGW: winapi's `winapi_<dll>`
  # copies of MinGW's own, and windows-targets' `windows.<version>`, which covers the Win32 API
  # through MinGW's import libraries of the same DLLs.
  flags=$(sed 's/\x1b\[[0-9;]*m//g' "$work/$name/link-flags.txt" | tr ' ' '\n' \
    | grep -v -e '^-lc$' -e '^$' -e '^-lwindows\.' | sed 's/^-lwinapi_/-l/' \
    | tr '\n' ' ' | sed 's/ $//')
  if [ "$goos" = windows ]; then
    flags="$flags -ladvapi32 -lole32 -loleaut32 -lshell32 -luser32 -lsecur32 -lcrypt32 -lncrypt -liphlpapi"
  fi
  echo "#cgo $goos,$goarch LDFLAGS: \${SRCDIR}/lib/$p/libnickel_lang.a $flags" >> "$work/link.go"
done

{
  echo "*/"
  echo 'import "C"'
} >> "$work/link.go"

cp "$work/header.h" include/nickel_lang.h
cp "$work/link.go" link.go
echo "$version" > RUST_NICKEL_VERSION
echo "lib/ now holds rust-nickel $version's C library."
